import assert from "node:assert/strict";
import test from "node:test";
import { observeResolvedContext } from "../src/context/calibration.js";
import { businessContextExample, vehicleContextExample } from "../src/context/examples.js";
import { createMeasurementStatement, renderMeasurement, validateMeasurementStatement } from "../src/context/measurement.js";
import { presentContextualOutput } from "../src/context/presentation.js";
import { applyUserContext } from "../src/context/reassess.js";
import type { ContextualOutput, UserContext, UserContextFactor } from "../src/context/types.js";
import { analyze } from "../src/engine.js";
import { createVolvoCase } from "../src/fixtures/volvo.js";

const now = new Date("2026-08-13T00:00:00.000Z");

function materialFactor(action: "ACT" | "WAIT" = "ACT"): UserContextFactor {
  return {
    id: "liquidity-context",
    description: "User requires access to the committed funds within six months.",
    contextType: "LIQUIDITY_REQUIREMENT",
    objectiveLink: "Maintain required liquidity",
    affectedConstraint: "Holding period",
    sourceOrigin: "USER_STATED",
    verificationStatus: "USER_CONFIRMED",
    potentialDecisionImpact: "May redirect the practical action without changing external evidence.",
    contextualImpact: { materiallyChangesAssessment: true, changes: ["CONCLUSION", "NEXT_ACTION"], assessment: "The user's liquidity requirement changes the practical fit of the base assessment.", contextualAction: action, nextAction: "Verify the six-month liquidity requirement before commitment." },
    sourceReferences: [],
    notes: [],
  };
}

function volvoContext(factor: UserContextFactor): { base: ReturnType<typeof analyze>; context: UserContext } {
  const base = analyze(createVolvoCase(), { now });
  return { base, context: { id: "volvo-user-context", decisionCaseId: base.decisionCase.id, factors: [factor], localAdvantages: [], notes: [] } };
}

test("raw measurements remain unchanged when user context is added", () => {
  const output = vehicleContextExample();
  const measurements = structuredClone(output.measurements);
  presentContextualOutput(output, "CONDENSED");
  presentContextualOutput(output, "BALANCED");
  presentContextualOutput(output, "AUDIT");
  assert.deepEqual(output.measurements, measurements);
});

test("user context cannot silently become external evidence", () => {
  const { base, context } = volvoContext(materialFactor());
  const evidence = structuredClone(base.decisionCase.evidence);
  const result = applyUserContext(base, context);
  assert.deepEqual(base.decisionCase.evidence, evidence);
  assert.deepEqual(result.baseAssessment.evidence, evidence);
  assert.equal(result.baseAssessment.evidence.some((item) => item.statement.includes("liquidity")), false);
  assert.equal(result.userContext.factors[0]!.sourceOrigin, "USER_STATED");
});

test("base assessment remains reproducible", () => {
  const first = vehicleContextExample().reassessment.baseAssessment;
  const second = vehicleContextExample().reassessment.baseAssessment;
  assert.deepEqual(first, second);
});

test("contextual assessment can differ without rewriting the base snapshot", () => {
  const { base, context } = volvoContext(materialFactor("ACT"));
  const snapshot = structuredClone(base.snapshot);
  const conclusion = structuredClone(base.conclusion);
  const result = applyUserContext(base, context);
  assert.notEqual(result.contextualAssessment.action, result.baseAssessment.conclusion.action);
  assert.deepEqual(result.baseAssessment.conclusion, conclusion);
  assert.deepEqual(result.baseAssessment.snapshot, snapshot);
  assert.equal(result.contextualAssessment.confidence, conclusion.confidence);
});

test("USER_STATED context remains distinguishable from verified facts", () => {
  const factor = vehicleContextExample().reassessment.userContext.localAdvantages[0]!;
  assert.equal(factor.sourceOrigin, "USER_STATED");
  assert.equal(factor.verificationStatus, "USER_CONFIRMED");
  assert.equal(factor.sourceReferences.length, 0);
});

test("loaded labels are not generated by default when precise measurements exist", () => {
  const measurement = createMeasurementStatement({ id: "population", metricName: "Registered population estimate", value: 180, unit: "vehicles", sourceReferences: ["registry"], interpretationStatus: "NONE", notes: [] });
  const rendered = renderMeasurement(measurement);
  assert.equal(rendered, "Registered population estimate: 180 vehicles");
  assert.equal(rendered.toLowerCase().includes("rare"), false);
  const invalid = { ...measurement, interpretationStatus: "SYSTEM_DEFINED_WITH_RULE" as const, interpretation: "Very rare vehicle", interpretationRuleId: "scarcity-v1" };
  assert.ok(validateMeasurementStatement(invalid).some((error) => error.includes("requires a definition")));
});

test("measurement source references survive creation and presentation", () => {
  const output = businessContextExample();
  assert.deepEqual(output.measurements[0]!.sourceReferences, ["supplier-quote"]);
  const balanced = presentContextualOutput(output, "BALANCED");
  assert.equal(balanced.mode, "BALANCED");
  assert.deepEqual(balanced.keyMeasurements[0]!.sourceReferences, ["supplier-quote"]);
});

test("CONDENSED surfaces only materially changing user context", () => {
  const material = vehicleContextExample();
  const visible = presentContextualOutput(material, "CONDENSED");
  assert.equal(visible.mode, "CONDENSED");
  assert.ok(visible.materialContext);

  const nonmaterial = structuredClone(material) as ContextualOutput;
  nonmaterial.reassessment.userContext.localAdvantages[0]!.contextualImpact.materiallyChangesAssessment = false;
  nonmaterial.reassessment.differences = [];
  nonmaterial.reassessment.contextualAssessment.appliedContextFactorIds = [];
  const hidden = presentContextualOutput(nonmaterial, "CONDENSED");
  assert.equal(hidden.mode, "CONDENSED");
  assert.equal(hidden.materialContext, undefined);
});

test("BALANCED and AUDIT expose measurement, context, origin, and base/context distinction", () => {
  const output = vehicleContextExample();
  const balanced = presentContextualOutput(output, "BALANCED");
  const audit = presentContextualOutput(output, "AUDIT");
  assert.equal(balanced.mode, "BALANCED");
  assert.equal(balanced.importantUserContext[0]!.sourceOrigin, "USER_STATED");
  assert.equal(audit.mode, "AUDIT");
  assert.deepEqual(audit.rawMeasurements, output.measurements);
  assert.deepEqual(audit.baseAssessment, output.reassessment.baseAssessment);
  assert.deepEqual(audit.contextualAssessment, output.reassessment.contextualAssessment);
});

test("historical snapshots and engine scoring remain unchanged", () => {
  const { base, context } = volvoContext(materialFactor());
  const history = structuredClone(base.decisionCase.analysisHistory);
  const weights = structuredClone(base.snapshot.hypothesisWeights);
  const confidence = base.conclusion.confidence;
  applyUserContext(base, context);
  const rerun = analyze(createVolvoCase(), { now });
  assert.deepEqual(base.decisionCase.analysisHistory, history);
  assert.deepEqual(rerun.snapshot.hypothesisWeights, weights);
  assert.equal(rerun.conclusion.confidence, confidence);
});

test("descriptive context calibration records improvement and misleading context without changing formulas", () => {
  const observation = observeResolvedContext({ caseId: "resolved-context", contextMateriallyImprovedDecision: true, incorrectOrMisleadingContextFactorIds: ["bad-context"], overestimatedAdvantageFactorIds: ["advantage"], measurementFirstReducedInterpretiveError: true, loadedLabelWouldHaveMisled: true, notes: [] });
  assert.equal(observation.contextImprovedDecision, true);
  assert.equal(observation.misleadingContextCount, 1);
  assert.equal(observation.overestimatedAdvantageCount, 1);
  assert.equal(observation.measurementFirstHelped, true);
  assert.equal(observation.loadedLabelRiskObserved, true);
});
